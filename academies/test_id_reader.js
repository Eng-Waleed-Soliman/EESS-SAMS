const assert = require('node:assert/strict');
const { extract, digits, assess, needsRetry } = require('./static/academies/id-card-reader.js');
assert.equal(digits('٢٩٠٠١٠١٠١٠١٢٣٤'), '29001010101234');
assert.equal(digits('۲۹۰۰۱۰۱۰۱۰۱۲۳۴'), '29001010101234');
const labeled = extract('الاسم: أحمد محمد علي\n٢٩٠٠١٠١٠١٠١٢٣٤');
assert.equal(labeled.name, 'أحمد محمد علي');
assert.equal(labeled.nationalId, '29001010101234');
assert.equal(extract('الاسم\nأحمد محمد علي').name, 'أحمد محمد علي');
assert.equal(extract('29001010101234\n29001010101235').ambiguous, true);
assert.equal(extract('29001010101234\n29001010101235').nationalId, '');
assert.equal(extract('290010101012345').nationalId, '');
assert.equal(extract('1 2 3 4 5 6 7 8 9 0 1 2 3 4').nationalId, '');
assert.equal(extract('2 9 0 0 1 0 1 0 1 0 1 2 3 4').nationalId, '29001010101234');
assert.equal(extract('جمهورية مصر العربية\nبطاقة تحقيق الشخصية\nأحمد\nمحمد علي').name, '');
assert.equal(extract('جمهورية مصر العربية\nحدائق القبة القاهرة\nمدينة القاهرة').name, '');
assert.ok(extract('جمهورية مصر العربية\nأحمد\nمحمد علي').nameOptions.includes('أحمد محمد علي'));
assert.ok(!extract('جمهورية مصر العربية').nameOptions.length);
assert.equal(extract('‎الاسم: أحمد محمد علي‏\n‎٢٩٠٠١٠١٠١٠١٢٣٤‏').nationalId, '29001010101234');
assert.equal(extract('‎الاسم: أحمد محمد علي‏').name, 'أحمد محمد علي');
assert.equal(extract('‎أَحْمَد\nمُحَمَّد عَلِي‏', 'name').name, 'أحمد محمد علي');
assert.equal(extract('٢٩٠٠١٠١٠١٠١').partialId, '29001010101');
assert.equal(extract('٢٩٠٠١٠١٠١٠١').nationalId, '');
console.log('ID reader extraction tests passed');
assert.equal(extract('LP29001010101234').nationalId, '');
assert.equal(extract('LP36335593').partialId, '');
const sample = {text: 'الاسم: أحمد محمد علي\n29001010101234', confidence: 95};
assert.equal(assess({...sample, confidence: 40}, 'name').name, '');
assert.equal(assess({...sample, confidence: 40}, 'number').nationalId, '');
assert.deepEqual(assess({...sample, confidence: 40}, 'card').nameOptions, []);
assert.equal(assess({text: sample.text}, 'number').nationalId, '');
assert.equal(assess(sample, 'number').name, '');
assert.equal(assess(sample, 'name').nationalId, '');
assert.equal(assess(sample, 'card').name, '');
assert.equal(needsRetry(assess({text: 'أحمد محمد علي\n36335593', confidence: 95}, 'card'), 'card'), true);
assert.equal(assess({text: 'أحمد محمد علي\nش الجندي', confidence: 95}, 'name').name, 'أحمد محمد علي');
